def _drawio(nodes):
    """生成模拟的 draw.io XML，节点标签来自 nodes。"""
    cells = "".join(
        f'<mxCell id="{i}" value="{n}" vertex="1"/>' for i, n in enumerate(nodes)
    )
    return (
        '<mxfile><diagram><mxGraphModel><root>'
        f'<mxCell id="0"/><mxCell id="1" parent="0"/>{cells}'
        '</root></mxGraphModel></diagram></mxfile>'
    )


