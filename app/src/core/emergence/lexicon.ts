/**
 * 能当「文种尾巴」的词。
 *
 * 在 DOC_KIND_WORDS 之外补了几个单字容器词（稿/单/表/图/册），
 * 因为真实文件里「演讲稿」「资源申请单」这种两字修饰 + 一个文种字的写法很常见，
 * 而它们显然不是「一件事」。
 *
 * 刻意**不收**『计划』『办法』『制度』『规范』：`逐浪计划`、`考核办法修订`
 * 这类以它们结尾的名字经常是真的项目名，宁可留着让用户删。
 */
export const DOC_KIND_TAILS: string[] = [
  ...DOC_KIND_WORDS,
  '稿', '单', '表', '图', '册', '台账', '表格', '正文', '附件', '记录',
].sort((a, b) => b.length - a.length)

/** 前缀超过这个长度，说明「文种词」前面挂着一个真专名，不能当语气词杀掉 */
const MAX_DOC_KIND_PREFIX = 4

/**
 * 判定「这个词就是文种，不是事项」。
 *
 * 判据：以文种词结尾，且前面只剩 ≤4 字的修饰。
 *   `演讲稿`      前缀「演讲」2 字   → 是文种
 *   `进展汇报`    前缀「进展」2 字   → 是文种
 *   `ppt修改`     前缀「ppt」 3 字   → 是文种
 *   `资源申请单`  前缀「资源申请」4 字 → 是文种
 *   `服务器领用交接单` 前缀 9 字     → 不是，这是具体那件事
 *   `智能工厂开展汇报` 前缀 6 字     → 不是
 */
export function isDocKindPhrase(term: string): boolean {
  const t = term.trim()
  for (const tail of DOC_KIND_TAILS) {
    if (t.length <= tail.length) continue
    if (!t.endsWith(tail)) continue
    if (t.length - tail.length <= MAX_DOC_KIND_PREFIX) return true
  }
  return false
}

/**
 * 光秃秃的组织泛称：这类词单独出现时不可能是一件具体的事。
 * 全是语言级词汇（任何行业都这么叫），不含行业名。
 */
export const BARE_ORG_WORDS = new Set([
  '集团', '公司', '单位', '部门', '总部', '分公司', '子公司', '总公司',
  '董事会', '办公室', '项目组', '技术室', '工作组',
])

/**
 * 判断一个词是否是组织名。
 *
 * 反例说明为什么不能一刀切：`油化厂`、`钻采院` 也以组织后缀结尾，
 * 但它们恰恰是真实事项。所以单字后缀要求前面至少 4 个字才算组织名，
 * 多字后缀要求前面至少 2 个字。
 */
export function isOrgName(term: string): boolean {
  if (BARE_ORG_WORDS.has(term)) return true
  for (const suf of ORG_SUFFIXES) {
    if (!term.endsWith(suf)) continue
    const extra = term.length - suf.length
    if (extra <= 0) continue
    if (suf.length === 1 ? extra >= 4 : extra >= 2) return true
  }
  return false
}
